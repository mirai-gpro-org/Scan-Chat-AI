-- ============================================================================
-- ユーザーがスキャンした検査票の「解析した md」を保存する列を足す。
--
-- 【なぜ要るか】
-- ユーザーのスキャンは、これまで **アプリ自身の DB に 1 行も残していなかった**。
-- 経路は 撮影/UL → 確認 → Elith 用に S3 へ書き出し → /chat で終わりで、
-- `test_artifacts` に insert するのは admin の取込 (lab-results/upload) だけだった。
-- そのため検査結果ページに「人間ドック / 健康診断」の中身を出せなかった。
--
-- 【なぜ列で持つのか (ファイルにしない)】
-- md は**原本ではなく解析結果 (派生データ)**。同じ派生データである測定値を
-- `test_artifacts.measurements` (jsonb) に持たせた 20260820000010 と同じ流儀に揃える。
--   原本 (撮影画像・アップロード PDF)  … ファイル / オブジェクトストレージ
--   派生データ (測定値・解析 md)      … DB
-- 原本の保存は今回**見送り** (発注者判断 2026-09-04: 元々ユーザーの手元にあるもの)。
-- これにより 10 年保管バケット (Object Lock) の判断もここでは不要になる。
--
-- 既存行は null のまま。読み出し側は null を「まだ無い」として扱う。
-- ============================================================================

alter table diagnosis.test_artifacts
  add column if not exists scan_md text;

comment on column diagnosis.test_artifacts.scan_md is
  'ユーザー検証後の確定 Markdown (scan_md)。ユーザーのアプリ内スキャン経路だけが書く。'
  '原本ではなく解析結果なので DB に置く (測定値 = measurements jsonb と同じ層)。'
  'admin 取込 (lab-results/upload) 由来の行は null。';
